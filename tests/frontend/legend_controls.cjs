const assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const {readFileSync}=require('node:fs');
const path=require('node:path');
const dom=new JSDOM(`<form><select name="question_type"><option value="multiple_choice">Fechada</option><option value="open_ended">Aberta</option></select><input name="answer_lines"><input name="options"><input name="correct_answer"><div data-question-type-editor><textarea data-alternatives-input>[]</textarea><select data-legend-catalog><option value="">Sem legenda</option><option>Confusão de sinal</option></select><div data-alternative-controls><div data-alternative-list></div><button type="button" data-add-alternative>Adicionar</button><p data-alternative-status></p></div></div></form>`,{runScripts:'outside-only'});
const w=dom.window,d=w.document;
w.eval(readFileSync(path.resolve(__dirname,'../../src/static/js/question-types.js'),'utf8'));
d.dispatchEvent(new w.Event('DOMContentLoaded'));
const rows=d.querySelectorAll('.alternative-block');
rows[0].querySelector('textarea').value='Certa';rows[0].querySelector('input[type=radio]').click();
rows[1].querySelector('textarea').value='Errada';
rows[1].querySelector('[data-new-legend]').value='Confunde <numerador> com denominador';
rows[1].querySelector('details button').click();
let data=JSON.parse(d.querySelector('[data-alternatives-input]').value);
assert.equal(data[1].legend,'Confunde <numerador> com denominador');
assert.equal(d.querySelector('numerador'),null);
assert.ok([...rows[0].querySelector('select').options].some(x=>x.value===data[1].legend));
rows[0].querySelector('[aria-label="Remover alternativa"]').click();
data=JSON.parse(d.querySelector('[data-alternatives-input]').value);assert.equal(data[0].legend,'Confunde <numerador> com denominador');
d.querySelector('[name=question_type]').value='open_ended';d.querySelector('[name=question_type]').dispatchEvent(new w.Event('change'));
assert.ok(d.querySelector('[data-alternative-legend]').disabled);
dom.window.close();console.log('Legend controls passed: create/select, reuse, removal, safe text and question-type switching.');
