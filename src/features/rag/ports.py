"""Application boundaries. Adapters return JSON-safe values, never ORM entities."""
from typing import Any, Protocol


class ModelProvider(Protocol):
    @property
    def name(self) -> str: ...
    async def acomplete(self, messages: list[dict], *, structured: bool = False,
                        on_partial: Any = None, user_id: Any = None,
                        allow_question_tools: bool = True) -> Any: ...


class KnowledgeSource(Protocol):
    def search(self, query: str) -> list[dict]: ...


class RagRepository(Protocol):
    async def context(self, user_id) -> dict: ...
    async def read(self, user_id, tool: dict) -> dict: ...
    async def validate(self, user_id, proposal: dict) -> dict: ...
    async def execute(self, user_id, generation: str, proposal: dict) -> dict: ...
    async def load(self, user_id) -> tuple[str, list[dict]]: ...
    async def append(self, user_id, generation, role, content, metadata=None) -> bool: ...
    async def clear(self, user_id) -> str: ...
    async def page(self, user_id, generation, before) -> list[dict]: ...

    async def issue_token(self, user_id) -> str: ...
    async def authorize_token(self, token: str) -> str: ...
    async def read_by_token(self, token: str, tool: dict) -> dict: ...
